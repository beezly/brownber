export const CHAR_W = 6;
export const LINE_H = 9;

export function textWidth(s: string) {
  return s.length * CHAR_W - 1;
}

/** Draw pixel text into a Graphics object. Returns the width drawn. */
export function drawText(
  g: Phaser.GameObjects.Graphics,
  text: string,
  x: number,
  y: number,
  color: number,
  shadow?: number,
  scale = 1,
): number {
  const s = text.toUpperCase();
  if (shadow !== undefined) drawRaw(g, s, x + scale, y + scale, shadow, scale);
  drawRaw(g, s, x, y, color, scale);
  return textWidth(s) * scale;
}

function drawRaw(g: Phaser.GameObjects.Graphics, s: string, x: number, y: number, color: number, k = 1) {
  g.fillStyle(color, 1);
  for (let i = 0; i < s.length; i++) {
    const glyph = G[s[i]] ?? G['?'];
    const gx = x + i * CHAR_W * k;
    for (let r = 0; r < 7; r++) {
      const bits = glyph[r];
      if (!bits) continue;
      for (let c = 0; c < 5; c++) {
        if (bits & (0x10 >> c)) g.fillRect(gx + c * k, y + r * k, k, k);
      }
    }
  }
}

export function drawTextCentered(
  g: Phaser.GameObjects.Graphics,
  text: string,
  cx: number,
  y: number,
  color: number,
  shadow?: number,
  scale = 1,
) {
  drawText(g, text, Math.round(cx - (textWidth(text) * scale) / 2), y, color, shadow, scale);
}

/** Word-wrap text to lines of at most `max` characters. */
export function wrap(text: string, max: number): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    if (!cur) cur = w;
    else if ((cur + ' ' + w).length <= max) cur += ' ' + w;
    else {
      lines.push(cur);
      cur = w;
    }
  }
  if (cur) lines.push(cur);
  return lines;
}

/** Centered text where each of the 7 glyph rows has its own colour (for chrome/gradient titles). */
export function drawTextRows(
  g: Phaser.GameObjects.Graphics,
  text: string,
  cx: number,
  y: number,
  rowColors: number[],
  scale = 1,
  shadow?: number,
) {
  const str = text.toUpperCase();
  const x0 = Math.round(cx - (textWidth(str) * scale) / 2);
  const paint = (ox: number, oy: number, colorFor: (r: number) => number) => {
    for (let i = 0; i < str.length; i++) {
      const glyph = G[str[i]] ?? G['?'];
      const gx = ox + i * CHAR_W * scale;
      for (let r = 0; r < 7; r++) {
        const bits = glyph[r];
        if (!bits) continue;
        g.fillStyle(colorFor(r), 1);
        for (let c = 0; c < 5; c++) if (bits & (0x10 >> c)) g.fillRect(gx + c * scale, oy + r * scale, scale, scale);
      }
    }
  };
  if (shadow !== undefined) paint(x0 + scale, y + scale, () => shadow);
  paint(x0, y, (r) => rowColors[Math.min(r, rowColors.length - 1)]);
}
